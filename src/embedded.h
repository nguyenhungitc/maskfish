// The network embedded in the binary (CMake option MASKFISH_EMBED_NET, the file MASKFISH_NET_FILE), on which
// EvalFile falls back when it names no file or a file that cannot be loaded. It is defined by
// embedded_net.cpp, generated by CMakeLists.txt; a build of a universal binary (src/universal.h) gets it from
// the binary through an inherited memfd instead (embedded_fd.cpp), so that the binary holds it once.
#pragma once
#include <cstddef>
#include <cstdint>

namespace jq {

struct EmbeddedNet {
    const uint8_t* data = nullptr;
    std::size_t size = 0;  // 0: no network is embedded
};
EmbeddedNet embedded_net();

// A universal binary passes its embedded network to the build it starts through this descriptor.
constexpr const char* EMBEDDED_NET_FD_ENV = "MASKFISH_UNIVERSAL_NET_FD";

}  // namespace jq
