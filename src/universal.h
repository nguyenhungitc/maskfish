// The universal binary (CMake option MASKFISH_UNIVERSAL; Linux x86-64 and arm64). It is the engine built for the
// baseline of the architecture, plus the engine built for every higher instruction set, embedded as executables.
// At startup dispatch() picks the highest build the CPU runs and executes it from memory (memfd_create, fexecve)
// in the same process; when that build is the baseline, or when it cannot be started, the baseline runs here.
// Every build gives the same evaluations and the same bench signature (the network's arithmetic is integer).
#pragma once

namespace jq::universal {

struct Slice {  // one embedded build (universal_slices.cpp, generated by CMakeLists.txt), lowest first
    const char* name;
    const unsigned char* begin;
    const unsigned char* end;
};
extern const Slice kSlices[];
extern const int kNumSlices;
extern const char* const kBaseline;  // the build of the binary itself

// Runs the best build for the CPU, or the one named by MASKFISH_UNIVERSAL_ARCH (`list` lists them and exits).
// Returns only when the baseline is to run in this process.
void dispatch(char** argv);

}  // namespace jq::universal
