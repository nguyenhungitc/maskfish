#!/usr/bin/env bash
# =============================================================================
#  Maskfish — training pipeline for one "generation"
#
#  build engine → check → (gen0 net) → generate train + val data → train
#  → verify the exported nets → SPRT against the current net → promote
#
#  Where the data comes from (--source):
#     self     Maskfish (current net) plays and scores its own positions
#              (`maskfish selfplay`, TrainRecords of 112 bytes).
#     distill  Maskfish (current net) plays, the reference engine scores every
#              position kept (tools/label.py).
#     ref      the reference engine plays both sides and scores its positions
#              (tools/match.py --scores, then tools/games2rec.py; the referee of
#              tools/native judges every move). Used for gen0.
#  Scores of the reference engine are converted to Maskfish units: its score →
#  win probability scale K is fitted on the first data it scored and saved in
#  data/REF_NAME.scale, and every file it scores is rescaled by MASKFISH_K / K
#  (scripts/datatool.py; MASKFISH_K is fitted the same way on Maskfish's own
#  scores, data/maskfish.scale). FILE.src names the engine that scored FILE.
#  Training (train/train.py) starts from the current net: runs/genN/best.pt when
#  the pipeline trained it, else the net file itself (e.g. the published net).
#  The reference engine is any UCI engine with Maskfish's FEN and move notation;
#  only the REF_* settings name it.
#
#  Sends a Telegram ✅ after every step; on error sends ❌ at once with the tail
#  of the log, then stops. Every step that is done is not done again when the
#  script is run again with the same -g (the files of the step are its record).
#
#  Generation numbering:
#     -g N : nets/genN.nnue is the CURRENT net
#            data/genN.bin, data/valN.bin are generated by that net
#            train on the data of generations TRAIN_FROM..N  →  runs/gen(N+1)/
#            →  nets/gen(N+1).nnue when it wins the SPRT
#     gen0: nets/gen0.nnue is INIT_NET, else nets/maskfish.nnue (scripts/net.sh);
#     with --source ref no gen0 net is needed (gen1 is then promoted without SPRT).
#
#  Exit status: 0 = a new net was promoted (or the requested part is done),
#               3 = trained but not promoted (lost the SPRT), 1 = error, 2 = usage.
#
#  Examples:
#     scripts/pipeline.sh -g 0 --source ref       # reference engine games → train gen1
#     scripts/pipeline.sh -g 1 --source distill   # gen1 plays, the reference engine scores → gen2
#     scripts/pipeline.sh -g 7 --source self      # gen7 plays and scores → gen8
#     scripts/pipeline.sh -g 1 --gen-only --tag m2   # only generate data, on a second machine
#     scripts/pipeline.sh -g 1 --train-only       # only train / verify / SPRT on existing data
#     scripts/pipeline.sh --build-only            # only build build/pipeline (engine, referee library)
#     scripts/pipeline.sh --test-telegram
#
#  Config: scripts/pipeline.env (copy of pipeline.env.example) or --config.
#  Hardware parameters left empty are chosen for the machine (scripts/hw_probe.py).
# =============================================================================
set -uo pipefail
if (( BASH_VERSINFO[0] < 4 || (BASH_VERSINFO[0] == 4 && BASH_VERSINFO[1] < 4) )); then
  echo "bash >= 4.4 required (this is $BASH_VERSION)" >&2; exit 2
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT" || exit 1                  # nets/, data/, runs/, logs/ live at the root (ignored by git)

usage() { sed -n '2,47p' "$0" | sed 's/^# \{0,1\}//'; cat <<'EOF'
Options:
  -g, --gen N          Generation number of the current net (required, except --build-only, --test-telegram)
      --source S       self | distill | ref (default: $SOURCE, else ref for -g 0 without a net, self otherwise)
      --gen-only       Only: build, check, gen0 net, generate train + val data
      --train-only     Only: build, train, verify, SPRT, promote (on the data already there)
      --build-only     Only: build (build/pipeline), then exit
      --tag NAME       Machine / data batch name (data/genN_NAME.bin), for several machines
      --config FILE    Config file (default: scripts/pipeline.env if present)
      --skip-check     Skip the checks of the engine (perft, network, HNN evaluator, difftest)
      --skip-match     Skip the SPRT: the best epoch is promoted
      --rebuild        Build everything again (otherwise the build is incremental, at every run)
      --force          Generate the data and train again even if present (deletes them first)
      --dry-run        Only print the commands; run nothing, send no real Telegram message
      --test-telegram  Send a test message and exit
  -h, --help
EOF
}

GEN=""; MODE="full"; TAG=""; CONFIG=""; SOURCE_CLI=""; SKIP_CHECK=0; SKIP_MATCH=0
REBUILD=0; FORCE=0; DRY_RUN=0; TEST_TG=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    -g|--gen)        GEN="${2:-}"; shift 2 ;;
    --source)        SOURCE_CLI="${2:-}"; shift 2 ;;
    --gen-only)      MODE="gen"; shift ;;
    --train-only)    MODE="train"; shift ;;
    --build-only)    MODE="build"; shift ;;
    --tag)           TAG="${2:-}"; shift 2 ;;
    --config)        CONFIG="${2:-}"; shift 2 ;;
    --skip-check)    SKIP_CHECK=1; shift ;;
    --skip-match)    SKIP_MATCH=1; shift ;;
    --rebuild)       REBUILD=1; shift ;;
    --force)         FORCE=1; shift ;;
    --dry-run)       DRY_RUN=1; shift ;;
    --test-telegram) TEST_TG=1; shift ;;
    -h|--help)       usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

# ----------------------------------------------------------------------------- config
if [[ -z "$CONFIG" && -f "$SCRIPT_DIR/pipeline.env" ]]; then CONFIG="$SCRIPT_DIR/pipeline.env"; fi
if [[ -n "$CONFIG" ]]; then
  [[ -f "$CONFIG" ]] || { echo "Config file not found: $CONFIG" >&2; exit 2; }
  # shellcheck disable=SC1090
  source "$CONFIG"
fi
if [[ -z "${PYTHON:-}" ]]; then
  if [[ -x "$ROOT/.venv/bin/python" ]]; then PYTHON="$ROOT/.venv/bin/python"; else PYTHON=python3; fi
fi
: "${TG_BOT_TOKEN:=}"; : "${TG_CHAT_ID:=}"; : "${TG_EPOCH_EVERY:=5}"; : "${TG_NAME:=$(hostname -s 2>/dev/null || hostname)}"
: "${BUILD_ARCH:=native}"         # native | portable | a -march value (x86-64-v3, ...)
: "${BUILD_OPTS:=}"               # more CMake options, e.g. "-DMASKFISH_LTO=ON"
: "${INIT_NET:=}"                 # gen0 net (default: nets/maskfish.nnue, fetched by scripts/net.sh)
# reference engine
: "${JIEQI_DIR:=$ROOT/jieqi}"
: "${REF_ENGINE:=$JIEQI_DIR/ref-engine}"
: "${REF_NET=$(ls "$JIEQI_DIR"/ref-engine*.nnue 2>/dev/null | sort | tail -1)}"  # sent as EvalFile; empty: none
: "${REF_OPTS=}"                  # its UCI options, as Name=Value,Name=Value
: "${REF_NAME:=$(basename "$REF_ENGINE")}"
: "${REF_GEN_NODES:=10000}"       # nodes per move when it plays the games (--source ref)
: "${REF_GEN_DEPTH:=0}"           # >0: depth instead of REF_GEN_NODES
: "${REF_LABEL_GO:=nodes 20000}"  # its search of every scored position (--source distill), as "go" arguments
: "${REF_HASH:=16}"
: "${ENGINE_TIMEOUT:=600}"        # seconds to wait for one search of an engine
: "${MASKFISH_K:=}"               # Maskfish's score → win probability scale; empty: fitted once (data/maskfish.scale)
: "${SOURCE:=}"
# data generation
: "${GAMES:=20000}"; : "${VAL_GAMES:=500}"; : "${NODES:=5000}"; : "${DEPTH:=0}"
: "${RANDOM_PLIES:=8}"            # random opening plies of every game (0..N)
: "${GEN_HASH:=16}"
: "${GEN_OPTS:=}"                 # UCI options of the generating engine, as Name=Value,Name=Value
: "${GEN_THREADS:=}"              # empty = auto: cores - 1
: "${LABEL_WORKERS:=}"            # empty = auto: cores - 1
: "${SEED_BASE:=}"                # empty = derived from the generation and the tag
# training
: "${EPOCHS:=10}"; : "${LR:=}"; : "${LAMBDA:=0.7}"
: "${BATCH_SIZE:=}"               # empty = from the GPU memory (hw_probe.py)
: "${TRAIN_FROM:=0}"              # first generation whose data is trained on
: "${TRAIN_WINDOW:=0}"            # >0: only the data of the last N generations
: "${EXTRA_TRAIN:=}"              # more record files, e.g. "data/old.bin"
: "${INIT_FROM_CURRENT:=1}"       # gen>=1: start from runs/genN/best.pt (the state of the current net)
: "${STREAM:=}"                   # records in memory at a time (train.py --stream); empty = auto from RAM
: "${REQUIRE_GPU:=1}"             # 1 = fail if CUDA is not available
: "${TRAIN_ARGS:=}"               # more trainer options, e.g. "--qat-from 0.5" (a new net from scratch: "--width 512")
: "${TRAINER:=}"                  # another trainer script (same options as the default one)
# SPRT
: "${MATCH_NODES:=20000}"; : "${MATCH_MOVETIME:=0}"; : "${MATCH_TC:=}"
: "${MATCH_WORKERS:=}"            # empty = auto: cores - 1, limited by RAM
: "${MATCH_HASH:=16}"
: "${SPRT=0 5}"                   # empty = no SPRT: MATCH_MAX_PAIRS pairs, promoted if Elo - 95% error > 0
: "${SPRT_MODEL:=logistic}"       # logistic | normalized
: "${MATCH_MAX_PAIRS:=4000}"
: "${MATCH_EPOCHS:=best last}"    # candidates tried in order; the first one to win is chosen
: "${MATCH_OPTS:=}"               # UCI options of both engines, as Name=Value,Name=Value
: "${AUTO_PROMOTE:=1}"

NEXT=$(( ${GEN:-0} + 1 ))
EXT=hnn
SFX=${TAG:+_$TAG}
BUILD="$ROOT/build/pipeline"
ENGINE="$BUILD/maskfish"
export JIEQI_NATIVE_LIBRARY="$BUILD/lib/libjieqi_rules.so"
export HNN_JQNZ_TOOL="$BUILD/jqnz_tool"   # train.py decodes compressed nets with it
mkdir -p nets data runs logs
LOG="logs/pipeline-gen${GEN:-x}${SFX}.log"

# ----------------------------------------------------------------------------- telegram
tg() {   # tg TEXT: one message (the machine name first)
  local text="[$TG_NAME] $1"
  echo "TG: $text" | head -c 400; echo
  [[ $DRY_RUN == 1 || -z "$TG_BOT_TOKEN" || -z "$TG_CHAT_ID" ]] && return 0
  curl -fsS -m 30 -o /dev/null "https://api.telegram.org/bot$TG_BOT_TOKEN/sendMessage" \
    --data-urlencode "chat_id=$TG_CHAT_ID" --data-urlencode "text=${text:0:4000}" || echo "(Telegram failed)"
}
if [[ $TEST_TG == 1 ]]; then
  [[ -n "$TG_BOT_TOKEN" && -n "$TG_CHAT_ID" ]] || { echo "Set TG_BOT_TOKEN and TG_CHAT_ID in scripts/pipeline.env" >&2; exit 2; }
  tg "pipeline.sh: test message"; exit 0
fi
[[ $MODE == build || "$GEN" =~ ^[0-9]+$ ]] || { echo "-g N is required" >&2; usage >&2; exit 2; }

# one run at a time
if command -v flock > /dev/null 2>&1 && [[ $DRY_RUN == 0 ]]; then
  exec 9> logs/pipeline.lock
  flock -n 9 || { echo "Another pipeline.sh is running (logs/pipeline.lock)" >&2; exit 1; }
fi
exec > >(tee -a "$LOG") 2>&1
echo "=== $(date '+%F %T') pipeline.sh -g $GEN ${SOURCE_CLI:+--source $SOURCE_CLI} mode $MODE${TAG:+ tag $TAG}"

fail() { tg "❌ ${GEN:+gen$GEN: }$1"$'\n'"$(tail -n 15 "$LOG" | cut -c1-200)"; exit 1; }
STEP_T0=0
step() { STEP_NAME=$1; STEP_T0=$SECONDS; echo; echo "--- $(date '+%T') $1"; }
done_step() { tg "✅ ${GEN:+gen$GEN }$STEP_NAME ($(( (SECONDS - STEP_T0) / 60 )) min)${1:+: $1}"; }
run() {  # run CMD...: echo it, run it (not with --dry-run)
  echo "+ $*"
  [[ $DRY_RUN == 1 ]] && return 0
  "$@"
}
uci_opts() {  # uci_opts "A=1,B=2": setoption lines
  local IFS=,; for kv in $1; do [[ -n "$kv" ]] && printf 'setoption name %s value %s\n' "${kv%%=*}" "${kv#*=}"; done
}
spec_opts() {  # spec_opts "A=1,B=2" "EvalFile=x": a match.py option list
  local out="" a
  for a in "$@"; do [[ -n "$a" ]] && out="${out:+$out,}$a"; done
  printf '%s' "$out"
}
is_net() { [[ -s "$1" ]] && case "$(head -c 8 "$1" | od -An -c | tr -d ' \n')" in JQHNNUE1|JQHNNL01|JQHNNZ01) true ;; *) false ;; esac; }

# ----------------------------------------------------------------------------- hardware
eval "$("$PYTHON" scripts/hw_probe.py "$ROOT")" || fail "hw_probe.py failed"
AUTO_W=$(( HW_CORES > 1 ? HW_CORES - 1 : 1 ))
MEM_W=$(( HW_FREE_MB / 300 > 0 ? HW_FREE_MB / 300 : 1 ))     # ~150 MB per engine, two per game
: "${GEN_THREADS:=$AUTO_W}"; : "${LABEL_WORKERS:=$AUTO_W}"
: "${MATCH_WORKERS:=$(( AUTO_W < MEM_W ? AUTO_W : MEM_W ))}"
: "${BATCH_SIZE:=$HW_BATCH}"
: "${STREAM:=$(( HW_FREE_MB * 1024 * 1024 / 4 / 112 ))}"    # a quarter of the free RAM of records
echo "hardware: $HW_CORES CPUs ($HW_PHYS cores), RAM $HW_RAM_MB MB ($HW_FREE_MB free), disk $HW_DISK_MB MB free," \
     "GPU ${HW_GPU_NAME:-none} ${HW_VRAM_MB} MB; gen threads $GEN_THREADS, match workers $MATCH_WORKERS, batch $BATCH_SIZE"
SEED=${SEED_BASE:-$(( (GEN + 1) * 1000003 + $(printf '%s' "$TAG" | cksum | cut -d' ' -f1) % 100003 ))}

# ----------------------------------------------------------------------------- build
step build
# Incremental at every run, so that the engine and the referee library are those of the code checked out (a library
# of another ABI version is refused by tools/jieqi/native.py); --rebuild builds everything again.
case "$BUILD_ARCH" in
  native)   ARCH_OPTS=(-DMASKFISH_NATIVE=ON "-DCMAKE_CXX_FLAGS=") ;;
  portable) ARCH_OPTS=(-DMASKFISH_NATIVE=OFF "-DCMAKE_CXX_FLAGS=") ;;
  *)        ARCH_OPTS=(-DMASKFISH_NATIVE=OFF "-DCMAKE_CXX_FLAGS=-march=$BUILD_ARCH") ;;
esac
CLEAN=(); (( REBUILD )) && CLEAN=(--clean-first)
before=$(stat -c %Y "$ENGINE" "$JIEQI_NATIVE_LIBRARY" "$HNN_JQNZ_TOOL" 2> /dev/null | tr '\n' ' ')
# shellcheck disable=SC2086
run cmake -S . -B "$BUILD" -DCMAKE_BUILD_TYPE=Release "${ARCH_OPTS[@]}" $BUILD_OPTS > /dev/null || fail "cmake"
run cmake --build "$BUILD" -j "$HW_CORES" --target maskfish maskfish_difftest jieqi_rules jqnz_tool \
  "${CLEAN[@]}" > "logs/build.log" 2>&1 || { tail -n 20 logs/build.log; fail "build (logs/build.log)"; }
if [[ "$(stat -c %Y "$ENGINE" "$JIEQI_NATIVE_LIBRARY" "$HNN_JQNZ_TOOL" 2> /dev/null | tr '\n' ' ')" != "$before" ]]; then
  done_step "$BUILD_ARCH"
else
  echo "up to date: $ENGINE"
fi
[[ $MODE == build ]] && exit 0

# ----------------------------------------------------------------------------- gen0 net
CUR="nets/gen$GEN.nnue"
if [[ ! -f "$CUR" && $GEN == 0 ]]; then
  if [[ -n "$INIT_NET" ]]; then run cp "$INIT_NET" "$CUR" || fail "INIT_NET $INIT_NET"
  elif run sh scripts/net.sh && [[ -f nets/maskfish.nnue ]] && is_net nets/maskfish.nnue; then run cp nets/maskfish.nnue "$CUR"
  fi
fi
[[ -f "$CUR" ]] || CUR=""
SRC=${SOURCE_CLI:-$SOURCE}
[[ -n "$SRC" ]] || SRC=$([[ $GEN == 0 && -z "$CUR" ]] && echo ref || echo self)
case "$SRC" in self|distill|ref) ;; *) fail "unknown source $SRC" ;; esac
[[ -n "$CUR" || "$SRC" == ref || $MODE == train ]] || fail "no current net nets/gen$GEN.nnue (needed for --source $SRC)"
need_ref() { [[ -x "$REF_ENGINE" ]] || fail "reference engine $REF_ENGINE not found (REF_ENGINE in pipeline.env)"; }
echo "current net: ${CUR:-none}; source: $SRC"

# ----------------------------------------------------------------------------- check
if [[ $SKIP_CHECK == 0 && $MODE != train && ! -f "runs/gen$NEXT/.done-check$SFX" ]]; then
  step check
  if [[ $DRY_RUN == 0 ]]; then
    out=$(printf 'position startpos\nperft 3\nquit\n' | "$ENGINE") || fail "the engine does not start"
    grep -q '^perft 3 83907 ' <<< "$out" || fail "perft 3 is not 83907"
    if [[ -n "$CUR" ]]; then
      out=$(printf 'setoption name EvalFile value %s\nbench\nquit\n' "$ROOT/$CUR" | "$ENGINE")
      grep -q "load failed" <<< "$out" && fail "the engine cannot load $CUR"
      grep -q "Nodes searched" <<< "$out" || fail "bench with $CUR"
    fi
    "$PYTHON" tests/hnn_smoke.py "$ENGINE" > /dev/null 2>&1 \
      || fail "the network evaluator does not give the reference values (tests/hnn_smoke.py)"
    "$BUILD/maskfish_difftest" 100 "$GEN" > "logs/difftest-gen$GEN.log" 2>&1 || fail "maskfish_difftest (logs/difftest-gen$GEN.log)"
  fi
  [[ $DRY_RUN == 1 ]] || { mkdir -p "runs/gen$NEXT"; touch "runs/gen$NEXT/.done-check$SFX"; }
  done_step "perft, network, HNN evaluator, difftest"
fi

# ----------------------------------------------------------------------------- data
ref_spec() { printf 'ref%s=%s:%s' "$1" "$REF_ENGINE" "$(spec_opts "${REF_NET:+EvalFile=$REF_NET}" "$REF_OPTS" "Hash=$REF_HASH")"; }
ref_scale() {  # ref_scale FILE...: K of the reference engine (fitted on these files the first time)
  local f="data/$REF_NAME.scale"
  if [[ ! -s "$f" ]]; then "$PYTHON" scripts/datatool.py fit-k "$@" > "$f" || { rm -f "$f"; return 1; }; fi
  cat "$f"
}
selfplay() {  # selfplay OUT GAMES SEED
  local limit="nodes $NODES"; (( DEPTH > 0 )) && limit="depth $DEPTH"
  { uci_opts "$GEN_OPTS"
    echo "selfplay evalfile $ROOT/$CUR games $2 $limit threads $GEN_THREADS random $RANDOM_PLIES hash $GEN_HASH seed $3 out $1"
    echo quit; } | run "$ENGINE"
  [[ $DRY_RUN == 1 || -s "$1" ]] || return 1
}
maskfish_scale() {  # maskfish_scale [FILE]: Maskfish's K (MASKFISH_K, else fitted once on FILE, Maskfish's own scores)
  local f=data/maskfish.scale
  if [[ -n "$MASKFISH_K" ]]; then echo "$MASKFISH_K"; return; fi
  if [[ ! -s "$f" && -n "${1:-}" && -s "${1:-}" ]]; then "$PYTHON" scripts/datatool.py fit-k "$1" > "$f" || rm -f "$f"; fi
  if [[ -s "$f" ]]; then cat "$f"; else echo 430; fi   # no data of Maskfish's yet: the scale of the search (ChanceK)
}
rescale_ref() {  # rescale_ref RAW OUT: OUT = RAW in Maskfish units
  local k mk
  k=$(ref_scale "$1") || return 1
  mk=$(maskfish_scale)
  run "$PYTHON" scripts/datatool.py rescale "$1" "$2" "$("$PYTHON" -c "print($mk / $k)")" || return 1
  echo "scorer=$REF_NAME k=$k" > "$2.src"
}
gen_file() {  # gen_file OUT GAMES SEED: one data file of the source
  local out=$1 n=$2 seed=$3
  case "$SRC" in
    self)
      selfplay "$out" "$n" "$seed" || return 1
      [[ $DRY_RUN == 1 ]] || maskfish_scale "$out" > /dev/null
      echo "scorer=maskfish net=$CUR" > "$out.src" ;;
    distill)
      need_ref
      [[ -s "$out.raw" ]] || selfplay "$out.raw" "$n" "$seed" || return 1
      [[ $DRY_RUN == 1 ]] || maskfish_scale "$out.raw" > /dev/null   # Maskfish's scale, from its own scores
      run "$PYTHON" tools/label.py --in "$out.raw" --out "$out.ref" --go "$REF_LABEL_GO" --workers "$LABEL_WORKERS" \
        --timeout "$ENGINE_TIMEOUT" --engine "$REF_ENGINE:$(spec_opts "${REF_NET:+EvalFile=$REF_NET}" "$REF_OPTS" "Hash=$REF_HASH")" || return 1
      rescale_ref "$out.ref" "$out" || return 1
      rm -f "$out.raw" "$out.ref" ;;
    ref)
      need_ref
      local name; name="ref-$(basename "$out" .bin)"
      local lim=(--nodes "$REF_GEN_NODES"); (( REF_GEN_DEPTH > 0 )) && lim=(--depth "$REF_GEN_DEPTH")
      rm -rf "runs/$name"
      run "$PYTHON" tools/match.py --engine "$(ref_spec a)" --engine "$(ref_spec b)" --games "$n" "${lim[@]}" \
        --hash "$REF_HASH" --concurrency "$GEN_THREADS" --seed "$seed" --random-plies "$RANDOM_PLIES" --scores \
        --out "runs/$name" > "logs/$name.log" 2>&1 || { tail -n 5 "logs/$name.log"; return 1; }
      rm -f "$out.ref"
      run "$PYTHON" tools/games2rec.py "$name" --out "$out.ref" --engine "$ENGINE" || return 1
      rescale_ref "$out.ref" "$out" || return 1
      rm -f "$out.ref" ;;
  esac
}
if [[ $MODE != train ]]; then
  TRAIN_FILE="data/gen$GEN$SFX.bin"; VAL_FILE="data/val$GEN$SFX.bin"
  if [[ $FORCE == 1 ]]; then rm -f "$TRAIN_FILE" "$TRAIN_FILE".* "$VAL_FILE" "$VAL_FILE".*; fi
  if [[ ! -s "$TRAIN_FILE" || ! -s "$VAL_FILE" ]]; then
    step "data ($SRC)"
    # the training data first: the scale of a new reference engine is fitted on the first (largest) file
    [[ -s "$TRAIN_FILE" ]] || gen_file "$TRAIN_FILE" "$GAMES" "$SEED" || fail "training data ($SRC)"
    [[ -s "$VAL_FILE" ]] || gen_file "$VAL_FILE" "$VAL_GAMES" $(( SEED + 7 )) || fail "validation data ($SRC)"
    [[ $DRY_RUN == 1 ]] || done_step "$("$PYTHON" scripts/datatool.py stats "$TRAIN_FILE")"
  else
    echo "data: $TRAIN_FILE and $VAL_FILE are there"
  fi
fi
[[ $MODE == gen ]] && { tg "✅ gen$GEN data done (--gen-only)"; exit 0; }

# ----------------------------------------------------------------------------- train
OUT="runs/gen$NEXT"
mkdir -p "$OUT"
[[ $FORCE == 1 ]] && rm -f "$OUT"/best.* "$OUT"/last.* "$OUT/.done-train"
if [[ ! -f "$OUT/.done-train" ]]; then
  step train
  shopt -s nullglob
  first=$TRAIN_FROM
  (( TRAIN_WINDOW > 0 && GEN - TRAIN_WINDOW + 1 > first )) && first=$(( GEN - TRAIN_WINDOW + 1 ))
  DATA=(); VALS=()
  for (( g = first; g <= GEN; g++ )); do
    for f in data/gen$g.bin data/gen${g}_*.bin; do [[ "$f" == *.raw || "$f" == *.ref ]] || DATA+=("$f"); done
  done
  for f in data/val$GEN.bin data/val${GEN}_*.bin; do VALS+=("$f"); done
  # shellcheck disable=SC2206
  DATA+=($EXTRA_TRAIN)
  shopt -u nullglob
  (( ${#DATA[@]} )) || fail "no training data for generations $first..$GEN"
  (( ${#VALS[@]} )) || fail "no validation data data/val$GEN*.bin"
  VAL="${VALS[0]}"
  if (( ${#VALS[@]} > 1 )); then VAL="$OUT/val.bin"; run "$PYTHON" scripts/datatool.py cat "$VAL" "${VALS[@]}" || fail "val"; fi
  DEVICE_ARGS=()
  if [[ $DRY_RUN == 0 ]]; then
    "$PYTHON" -c "import torch, numpy" 2> /dev/null || fail "PyTorch and numpy are not available to $PYTHON (train/requirements.txt)"
    if ! "$PYTHON" -c "import torch, sys; sys.exit(0 if torch.cuda.is_available() else 1)" 2> /dev/null; then
      [[ $REQUIRE_GPU == 1 ]] && fail "CUDA is not available to $PYTHON (REQUIRE_GPU=1; REQUIRE_GPU=0 trains on the CPU, slowly)"
      DEVICE_ARGS=(--device cpu --threads "$HW_PHYS")   # train.py defaults to --device cuda
      echo "no CUDA: training on the CPU ($HW_PHYS threads)"
    fi
  fi
  INIT=()
  if [[ $INIT_FROM_CURRENT == 1 ]]; then
    if [[ -f "runs/gen$GEN/best.pt" ]]; then INIT=(--init "runs/gen$GEN/best.pt")
    elif [[ -n "$CUR" ]]; then INIT=(--init "$CUR")   # a net the pipeline did not train (gen0): its weights
    fi
  fi
  NREC=$("$PYTHON" scripts/datatool.py count "${DATA[@]}" | tail -n 1 | cut -d' ' -f1)
  STREAM_ARGS=(); (( NREC > STREAM )) && STREAM_ARGS=(--stream "$STREAM")
  echo "training on $NREC records of ${#DATA[@]} files: ${DATA[*]}"
  T=${TRAINER:-train/train.py}
  # shellcheck disable=SC2086
  CMD=("$PYTHON" "$T" "${DATA[@]}" --val-file "$VAL" --out "$OUT" --epochs "$EPOCHS" --batch "$BATCH_SIZE"
       --wt 0 --ws "$LAMBDA" --wr "$("$PYTHON" -c "print(round(1 - $LAMBDA, 6))")" ${LR:+--lr $LR}
       "${INIT[@]}" "${STREAM_ARGS[@]}" "${DEVICE_ARGS[@]}" $TRAIN_ARGS)
  echo "+ ${CMD[*]}"
  if [[ $DRY_RUN == 0 ]]; then
    "${CMD[@]}" 2>&1 | while IFS= read -r line; do
      echo "$line"
      if [[ "$line" == '{"epoch":'* ]] && (( TG_EPOCH_EVERY > 0 )); then
        ep=$(sed -E 's/.*"epoch": ?([0-9]+).*/\1/' <<< "$line")
        if (( ep % TG_EPOCH_EVERY == 0 )); then
          tg "gen$NEXT epoch $ep/$EPOCHS: $(sed -E 's/.*"val": ?([0-9.e-]+).*/val \1/' <<< "$line")"
        fi
      fi
    done
    (( PIPESTATUS[0] == 0 )) || fail "training"
    ls "$OUT"/best."$EXT" "$OUT"/last."$EXT" > /dev/null 2>&1 || fail "the trainer wrote no best.$EXT / last.$EXT"
    touch "$OUT/.done-train"   # not with --dry-run: a real run after it must train
  fi
  done_step "$NREC records"
fi

# ----------------------------------------------------------------------------- verify
step verify
CANDS=()
for e in $MATCH_EPOCHS; do
  f="$OUT/$e.$EXT"
  [[ $DRY_RUN == 1 ]] && { CANDS+=("$f"); continue; }
  [[ -f "$f" ]] || { echo "no $f"; continue; }
  is_net "$f" || { echo "$f is not a network"; continue; }
  dup=""; for c in "${CANDS[@]}"; do cmp -s "$c" "$f" && dup=$c; done
  [[ -n "$dup" ]] && { echo "$f: the same net as $dup"; continue; }
  out=$(printf 'setoption name EvalFile value %s\neval\nbench\nquit\n' "$ROOT/$f" | "$ENGINE" 2>&1)
  if grep -q "load failed" <<< "$out" || ! grep -q "Nodes searched" <<< "$out"; then echo "$f: the engine cannot use it"; continue; fi
  echo "$f: $(grep -m1 'loaded' <<< "$out" | sed 's/.*(\(.*\))/\1/'), bench $(grep 'Nodes searched' <<< "$out" | grep -o '[0-9]*')"
  CANDS+=("$f")
done
(( ${#CANDS[@]} )) || fail "no usable net among: $MATCH_EPOCHS"
done_step "${#CANDS[@]} candidates"

# ----------------------------------------------------------------------------- SPRT
WIN=""
summary_field() { "$PYTHON" -c "import json,sys; d=json.load(open('$1')); print(eval(sys.argv[1], {}, {'d': d}))" "$2"; }
if [[ $SKIP_MATCH == 1 || -z "$CUR" ]]; then
  WIN="${CANDS[0]}"
  echo "no SPRT ($([[ -z "$CUR" ]] && echo 'no current net' || echo '--skip-match')): $WIN"
else
  step sprt
  if [[ -n "$MATCH_TC" ]]; then LIM=(--tc "$MATCH_TC"); elif (( MATCH_MOVETIME > 0 )); then LIM=(--movetime "$MATCH_MOVETIME"); else LIM=(--nodes "$MATCH_NODES"); fi
  for c in "${CANDS[@]}"; do
    name="sprt-gen$NEXT-$(basename "$c" ".$EXT")"
    if [[ ! -f "runs/$name/summary.json" || $FORCE == 1 ]]; then
      rm -rf "runs/$name"
      # shellcheck disable=SC2086
      run "$PYTHON" tools/match.py --engine "new=$ENGINE:$(spec_opts "EvalFile=$ROOT/$c" "$MATCH_OPTS")" \
        --engine "old=$ENGINE:$(spec_opts "EvalFile=$ROOT/$CUR" "$MATCH_OPTS")" --games $(( 2 * MATCH_MAX_PAIRS )) \
        "${LIM[@]}" --hash "$MATCH_HASH" --concurrency "$MATCH_WORKERS" --seed $(( SEED + 11 )) \
        ${SPRT:+--sprt $SPRT --sprt-model $SPRT_MODEL} --out "runs/$name" > "logs/$name.log" 2>&1 \
        || { tail -n 5 "logs/$name.log"; fail "SPRT of $c"; }
    fi
    [[ $DRY_RUN == 1 ]] && { WIN="$c"; break; }
    s="runs/$name/summary.json"
    res=$(summary_field "$s" "d.get('sprt', {}).get('result', 'none')")
    elo=$(summary_field "$s" "'%+.1f [%+.1f, %+.1f] over %d pairs' % (d['pent']['elo'], d['pent']['elo_lo'], d['pent']['elo_hi'], d['pent']['pairs'])")
    lo=$(summary_field "$s" "d['pent']['elo_lo']")
    echo "$c: SPRT $res, Elo $elo"
    won=0
    if [[ "$res" == H1 ]]; then won=1
    elif [[ "$res" != H0 ]] && "$PYTHON" -c "import sys; sys.exit(0 if $lo > 0 else 1)"; then won=1   # no decision: Elo - error > 0
    fi
    if (( won )); then WIN="$c"; tg "✅ gen$NEXT $(basename "$c"): $res, Elo $elo"; break; fi
    tg "gen$NEXT $(basename "$c"): $res, Elo $elo"
  done
fi
[[ -n "$WIN" ]] || { tg "❎ gen$NEXT: no candidate beat gen$GEN; nets/gen$NEXT.nnue not made"; exit 3; }

# ----------------------------------------------------------------------------- promote
if [[ $AUTO_PROMOTE == 1 ]]; then
  run cp "$WIN" "nets/gen$NEXT.nnue" || fail "promote"
  base="${WIN%.*}"   # the state of the promoted net is runs/gen(N+1)/best.pt, the start of the next generation
  [[ "$base" != "$OUT/best" && -f "$base.pt" ]] && run cp "$base.pt" "$OUT/best.pt"
  tg "🏁 gen$NEXT promoted: nets/gen$NEXT.nnue ($(basename "$WIN"))"
else
  tg "🏁 gen$NEXT: $WIN won (AUTO_PROMOTE=0: copy it to nets/gen$NEXT.nnue)"
fi
exit 0
